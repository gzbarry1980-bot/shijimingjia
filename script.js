cartItems.addEventListener("click", (event) => {
  const incId = event.target.dataset.inc;
  const decId = event.target.dataset.dec;
  const id = incId || decId;
  if (!id) return;

  const item = cart.find((entry) => entry.id === id);
  if (!item) return;

  if (incId) {
    const product = Store.getProducts().find((entry) => entry.id === id);
    if (product && item.qty >= product.stock) return;
    item.qty += 1;
  }
  if (decId) item.qty -= 1;

  if (item.qty <= 0) {
    cart.splice(cart.indexOf(item), 1);
  }

  renderCart();
  renderProducts();
  if (activeDetailId) renderDetail(activeDetailId);
});

document.querySelector(".paypal-button").addEventListener("click", () => {
  if (!cart.length) {
    showToast(t("emptyAlert"));
    return;
  }

  const order = Store.createOrder(
    cart.map((item) => ({
      productId: item.id,
      name: productName(item.id),
      price: item.price,
      qty: item.qty,
    })),
    cart.reduce((sum, item) => sum + item.price * item.qty, 0)
  );

  cart.splice(0, cart.length);
  renderCart();
  renderProducts();
  if (activeDetailId) renderDetail(activeDetailId);
  closeCart();
  showToast(`${t("paypalAlert")} ${order.id}`);
});

