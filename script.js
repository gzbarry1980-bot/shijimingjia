function escapeHTML(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function localizedProductText(product, field, keyField) {
  if (product[field]) {
    return product[field][currentLang] || product[field].en || Object.values(product[field])[0];
  }
  return t(product[keyField]);
}

function productName(id) {
  const product = Store.getProducts().find((entry) => entry.id === id);
  if (!product) return t(`${id}Name`);
  return localizedProductText(product, "name", "nameKey");
}

function productCategory(product) {
  const haystack = `${product.sku} ${localizedProductText(product, "name", "nameKey")} ${localizedProductText(product, "tag", "tagKey")} ${localizedProductText(product, "label", "labelKey")}`.toLowerCase();
  if (haystack.includes("gift") || haystack.includes("礼") || haystack.includes("禮")) return "gift";
  if (haystack.includes("bag") || haystack.includes("袋泡") || haystack.includes("茶包")) return "bags";
  if (haystack.includes("10y") || haystack.includes("8y") || haystack.includes("6y") || haystack.includes("5y") || haystack.includes("3y") || haystack.includes("aged") || haystack.includes("year")) return "aged";
  return "daily";
}

