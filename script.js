function showToast(message) {
  toast.textContent = message;
  toast.classList.add("show");
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => {
    toast.classList.remove("show");
  }, 3200);
}

function renderCart() {
  saveCart();
  const totalQty = cart.reduce((sum, item) => sum + item.qty, 0);
  const subtotal = cart.reduce((sum, item) => sum + item.price * item.qty, 0);

  cartCount.textContent = totalQty;
  cartTotal.textContent = formatMoney(subtotal);

  if (!cart.length) {
    cartItems.innerHTML = `<p class="empty-cart">${t("emptyCart")}</p>`;
    return;
  }

  cartItems.innerHTML = cart.map((item) => `
    <div class="cart-item">
      <div>
        <strong>${escapeHTML(productName(item.id))}</strong>
        <span>${formatMoney(item.price)}</span>
      </div>
      <div class="qty-row" aria-label="${escapeHTML(productName(item.id))} quantity">
        <button type="button" data-dec="${item.id}" aria-label="${t("decrease")}">-</button>
        <span>${item.qty}</span>
        <button type="button" data-inc="${item.id}" aria-label="${t("increase")}">+</button>
      </div>
    </div>
  `).join("");
}

